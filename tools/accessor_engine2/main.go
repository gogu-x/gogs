// accessor_engine2 provides reproducible accessors for simple player structures.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	dir := flag.String("dir", ".", "source directory")
	flag.Parse()
	if len(flag.Args()) == 0 {
		panic("provide structure names")
	}
	wanted := map[string]bool{}
	for _, name := range flag.Args() {
		wanted[name] = true
	}
	files, err := filepath.Glob(filepath.Join(*dir, "*.go"))
	if err != nil {
		panic(err)
	}
	fset := token.NewFileSet()
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "_accessors.go") || filepath.Base(path) == "deepcopy.go" {
			continue
		}
		source, err := parser.ParseFile(
			fset, path, nil, 0,
		)
		if err != nil {
			panic(err)
		}
		for _, decl := range source.Decls {
			general, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range general.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || !wanted[typeSpec.Name.Name] {
					continue
				}
				structure, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					continue
				}
				var out bytes.Buffer
				fmt.Fprintf(&out, "// Code generated by accessor_engine2. DO NOT EDIT.\npackage %s\n", source.Name.Name)
				for _, field := range structure.Fields.List {
					var fieldType bytes.Buffer
					if err := format.Node(&fieldType, fset, field.Type); err != nil {
						panic(err)
					}
					for _, name := range field.Names {
						fmt.Fprintf(
							&out, "// Get%s returns the field value.\nfunc (v *%s) Get%s() %s { if v == nil { var zero %s; return zero }; return v.%s }\n",
							name, typeSpec.Name, name, fieldType.String(), fieldType.String(), name,
						)
						fmt.Fprintf(
							&out, "// Set%s updates the field value.\nfunc (v *%s) Set%s(value %s) { v.%s = value }\n",
							name, typeSpec.Name, name, fieldType.String(), name,
						)
					}
				}
				formatted, err := format.Source(out.Bytes())
				if err != nil {
					panic(err)
				}
				if err := os.WriteFile(filepath.Join(*dir, strings.ToLower(typeSpec.Name.Name)+"_accessors.go"), formatted, 0644); err != nil {
					panic(err)
				}
				delete(wanted, typeSpec.Name.Name)
			}
		}
	}
	if len(wanted) > 0 {
		panic(fmt.Sprintf("structures not found: %v", wanted))
	}
}
